#!/usr/bin/env python3
"""Export this site's content into the judging trainer as its Prize Answers page.

The trainer already holds every figure this site uses, under docs/assets/img/fq and
docs/assets/img/reg, so nothing is copied: the exported data points at the trainer's own
copies. Content stays authored here, in assets/d*.js, and the trainer is regenerated.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
QA = os.path.join(os.path.dirname(HERE), 'releaf-judging-qa')
QA_IMG = os.path.join(QA, 'docs', 'assets', 'img')
OUT = os.path.join(QA, 'docs', 'assets', 'js', 'prize-data.js')

DATA_FILES = [
    'data.js', 'd1-biomfg.js', 'd1b-biomfg.js', 'd2-measurement.js', 'd3-hardware.js',
    'd4-ihp.js', 'd4b-ihp.js', 'd5-general.js', 'd5b-general.js',
]


def where(name):
    """the trainer's own path for a figure file, or None if it does not hold it"""
    for sub in ('fq', 'reg', ''):
        if os.path.exists(os.path.join(QA_IMG, sub, name)):
            return 'assets/img/' + (sub + '/' if sub else '') + name
    return None


def main():
    if not os.path.isdir(QA):
        sys.exit('judging trainer not found at ' + QA)

    with open(os.path.join(HERE, 'assets', 'figs.js'), encoding='utf-8') as fh:
        figs = json.loads(re.sub(r'^.*?var FIGS = ', '', fh.read(), flags=re.S).rstrip().rstrip(';'))

    missing = []
    for fid, fig in figs.items():
        path = where(fig['img'])
        if path is None:
            missing.append(fid + ' (' + fig['img'] + ')')
        else:
            fig['img'] = path
    if missing:
        sys.exit('the trainer does not hold: ' + ', '.join(missing))

    parts = ['/* Generated by prize-answer/tools/export_trainer.py. Do not edit here.\n'
             ' * Content is authored in the prize-answer repository; figure paths point at this\n'
             ' * trainer\'s own image folders, so no image is duplicated. */\n']
    parts.append('var FIGS = ' + json.dumps(figs, ensure_ascii=False, indent=1) + ';\n')
    for name in DATA_FILES:
        with open(os.path.join(HERE, 'assets', name), encoding='utf-8') as fh:
            parts.append('\n/* ' + name + ' */\n' + fh.read())

    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(''.join(parts))

    print('%d figures resolved, %d files merged -> %s' % (len(figs), len(DATA_FILES), OUT))


if __name__ == '__main__':
    main()
